#!/usr/bin/env python3
"""Boundary and mathematical verification for Round 742:
HyDE Hypothetical Document Embeddings (Gao, Ma, Lin, & Callan, ACL 2023, arXiv:2212.10496).

Verifies:
1. Section 3.2 Equations 2-8: Decomposition of zero-shot dense retrieval into
   (a) generative hypothetical document sampling d_hat_k ~ g(q_{ij}, INST_i) from an instruction-following LLM, and
   (b) document-space contrastive encoding and expectation averaging:
       v_hat_{q_{ij}} = (1 / (N + 1)) * ( sum_{k=1}^N f(d_hat_k) + f(q_{ij}) ),
   where f = enc_con is an unsupervised contrastive document encoder that acts as a lossy bottleneck
   filtering out hallucinated entity details while preserving document-level relevance features.
2. Retrieval via inner product <v_hat_{q_{ij}}, f(d)> in the corpus document embedding space resolves
   the query-document vocabulary/style mismatch that causes direct <f(q_{ij}), f(d)> to fail.
"""

import math


def dot(u, v):
    return sum(a * b for a, b in zip(u, v))


def main():
    # Suppose document representation space has 4 dimensions:
    # dim 0: answer-domain semantic content (high in true answer document and hypothetical answer passages)
    # dim 1: interrogative/question surface phrasing (high in raw query and question-like distractor doc)
    # dims 2..3: orthogonal noise axes where individual hallucinated details cancel out under averaging
    real_corpus = [
        [0.92, 0.25, 0.01, -0.01],  # doc 0: true relevant answer document
        [0.20, 0.88, 0.05, -0.02],  # doc 1: non-relevant distractor sharing question phrasing
        [0.10, 0.40, -0.10, 0.15],  # doc 2: non-relevant document
    ]

    # Raw short query q has high interrogative phrasing (dim 1 = 0.85) and low answer-domain content (dim 0 = 0.22),
    # so direct unsupervised document-document encoder f(q) misranks distractor doc 1 above true doc 0!
    f_q = [0.22, 0.85, 0.0, 0.0]

    # N = 4 hypothetical answer documents generated by InstructLM g(q, INST), encoded by f = enc_con:
    # Each translates the query into answer-domain semantics (dim 0 ~ 0.90, dim 1 ~ 0.25),
    # with zero-mean hallucination noise on dims 2..3
    f_d_hats = [
        [0.91, 0.24, 0.25, -0.20],
        [0.89, 0.26, -0.22, 0.18],
        [0.92, 0.23, 0.15, 0.22],
        [0.88, 0.27, -0.18, -0.20],
    ]

    # Equation 7: average of N hypothetical document embeddings
    n = len(f_d_hats)
    v_hyde_eq7 = [sum(f_d_hats[k][d] for k in range(n)) / n for d in range(4)]

    # Equation 8: including the query embedding f(q_{ij}) in the ensemble
    v_hyde_eq8 = [(sum(f_d_hats[k][d] for k in range(n)) + f_q[d]) / (n + 1) for d in range(4)]

    # Verify hallucination noise on dims 2..3 is compressed near zero by averaging
    assert abs(v_hyde_eq7[2]) < 0.01 and abs(v_hyde_eq7[3]) < 0.01

    # Compare inner-product retrieval rankings:
    raw_scores = [dot(f_q, d_vec) for d_vec in real_corpus]
    hyde7_scores = [dot(v_hyde_eq7, d_vec) for d_vec in real_corpus]
    hyde8_scores = [dot(v_hyde_eq8, d_vec) for d_vec in real_corpus]

    # Raw query f(q) misranks doc 1 above doc 0 (raw_margin < 0), whereas HyDE ranks true doc 0 first!
    raw_margin = raw_scores[0] - raw_scores[1]
    hyde_margin = hyde8_scores[0] - hyde8_scores[1]
    assert raw_margin < 0.0
    assert hyde_margin > 0.30
    assert max(range(3), key=lambda i: hyde7_scores[i]) == 0
    assert max(range(3), key=lambda i: hyde8_scores[i]) == 0

    print(
        f"HyDE verification passed: raw_margin={raw_margin:.4f} -> hyde_margin={hyde_margin:.4f}, "
        f"hyde8_scores={[round(s, 4) for s in hyde8_scores]}"
    )


if __name__ == "__main__":
    main()
