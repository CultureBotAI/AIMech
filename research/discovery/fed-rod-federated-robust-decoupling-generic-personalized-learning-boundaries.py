#!/usr/bin/env python3
"""Boundary verification for Round 444: Fed-RoD (Chen & Chao 2022, ICLR 2022, arXiv:2107.00778)."""
import math

def softmax(logits):
    m = max(logits)
    exps = [math.exp(z - m) for z in logits]
    s = sum(exps)
    return [e / s for e in exps]

def main():
    # Suppose class-conditional likelihoods P(x | y=c) for a test sample x are proportional to L_x = [0.70, 0.20, 0.10]
    L_x = [0.70, 0.20, 0.10]
    # Client m has skewed label prior P_m(y) = [0.10, 0.80, 0.10] (N_m = [10, 80, 10])
    N_m = [10.0, 80.0, 10.0]
    prior_m = [n / sum(N_m) for n in N_m]

    # True Bayes posterior on uniform generic test distribution P_U(y | x) is proportional to L_x:
    post_generic_true = [l / sum(L_x) for l in L_x]
    # True Bayes posterior on client m's skewed test distribution P_m(y | x) is proportional to prior_m[c] * L_x[c]:
    unnorm_pm = [prior_m[c] * L_x[c] for c in range(3)]
    post_client_true = [u / sum(unnorm_pm) for u in unnorm_pm]
    # Notice class 0 is Bayes-optimal globally (0.70), whereas class 1 is Bayes-optimal locally on client m (0.16/0.24 = 0.667)!
    assert post_generic_true[0] > post_generic_true[1]
    assert post_client_true[1] > post_client_true[0]

    # Under Fed-RoD Balanced Softmax (Eq. 6) with gamma=1:
    # P_BSM(y=c | x) = N_{m,c} * exp(g_c(x)) / sum_{c'} N_{m,c'} * exp(g_{c'}(x))
    # Minimizing expected BSM cross-entropy on client m's distribution P_m(y | x) yields
    # exp(g_c^*(x)) proportional to P_m(y=c | x) / N_{m,c} proportional to L_x[c] = P_U(y=c | x)!
    g_star = [math.log(L_x[c]) for c in range(3)]
    pred_generic_head = softmax(g_star)
    generic_bayes_err = max(abs(pred_generic_head[c] - post_generic_true[c]) for c in range(3))
    assert generic_bayes_err < 1e-15

    # Meanwhile, Fed-RoD's additive personalized head (Eq. 9-11) sets logit_P = g_star + h_P
    # where h_P = log(prior_m) (or generated by hypernetwork H^P(a_m)), recovering P_m(y | x) exactly!
    h_p = [math.log(prior_m[c]) for c in range(3)]
    pred_personalized_head = softmax([g_star[c] + h_p[c] for c in range(3)])
    personalized_bayes_err = max(abs(pred_personalized_head[c] - post_client_true[c]) for c in range(3))
    assert personalized_bayes_err < 1e-15

    print(f"[PASS] Round 444 Fed-RoD (Chen & Chao 2022): generic_bayes_err={generic_bayes_err:.2e}, personalized_bayes_err={personalized_bayes_err:.2e}, generic_top=0 ({post_generic_true[0]:.2f}) vs client_top=1 ({post_client_true[1]:.3f})")

if __name__ == "__main__":
    main()
